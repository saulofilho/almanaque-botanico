export function getCurrentSeasonHemisphereSouth(date: Date = new Date()): SeasonKey {
  const month = date.getMonth() + 1; // 1 = Jan, 12 = Dez
  const day = date.getDate();

  // Primavera: 22 de Setembro a 21 de Dezembro
  if ((month === 9 && day >= 22) || month === 10 || month === 11 || (month === 12 && day < 21)) {
    return "primavera";
  }
  // Verão: 21 de Dezembro a 20 de Março
  if ((month === 12 && day >= 21) || month === 1 || month === 2 || (month === 3 && day < 20)) {
    return "verao";
  }
  // Outono: 20 de Março a 21 de Junho
  if ((month === 3 && day >= 20) || month === 4 || month === 5 || (month === 6 && day < 21)) {
    return "outono";
  }
  // Inverno: 21 de Junho a 22 de Setembro
  return "inverno";
}
